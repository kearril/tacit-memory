namespace TacitMemory.Core.Skills;

/// <summary>
/// The memory skill, <c>TACIT_HOME/skills/tacit-memory/SKILL.md</c>: the frontmatter and the system part, both written
/// here in English, then the user's writing conventions from <c>prompts/skill.md</c> under a heading of their own.
/// </summary>
internal static class MemorySkill
{
    /// <summary>The skill's name, which is also its folder's name and the name of the client link.</summary>
    public const string Name = "tacit-memory";

    /// <summary>
    /// A client may show only about the first 100 characters of a description, or compress it to 160, so the moments to read
    /// the skill come first.
    /// </summary>
    private const string Description =
        "Read before writing or changing any memory, and again after a write_* tool refuses. Explains how each kind is written.";

    private const string Generated =
        "<!-- Generated by TacitMemory from its built-in text and prompts/skill.md. Edit prompts/skill.md; changes made here are overwritten. -->";

    private const string UserHeading = """
        ## User conventions
        The user's writing conventions below take precedence over the advice above, but they do not change how the tools are called.
        """;

    /// <summary>The system part: the writing guidance in English, the same in every skill; <c>show</c> prints it alone.</summary>
    internal const string SystemPart = """
        # Writing memory

        This page covers how to write each kind of memory well. The tool descriptions give the call format, short codes and limits; they win over anything here.

        Terms used below: a *matter* is one subject a page covers; the *brief* is the workstream map that `recall` returns for a workstream; a *trigger* is the one-line condition under which a domain's rules apply; a *lesson* is the rule an incident teaches; a *pointer* is a reference to where a fact already lives.

        ## Retrieval
        - Write queries in the memory language, with the words the memory itself would use. Search matches words, so a paraphrase or another language can miss what is there.
        - Narrow a search by kind, workstream or date when the question is about one of them.
        - Read a whole page for its overall picture; read only one section when you already know which one matters.
        - Every section shows the date it last changed. Judge a section that describes the current state by that date.

        ## Detail pages
        - A page covers one matter: update the page that already covers it instead of starting a second page for the same matter.
        - Pick the type by what the page records. The four types are incident, decision, entity and work; each example below shows one.
        - Title a page with the name the matter is known by; list the other names the user uses for it as aliases.
        - Organize a page into sections by facet, and put each new fact into the section it belongs to.
        - Write the date of each entry. Where the wording matters, quote the user's own words rather than a paraphrase.
        - Link a page to related pages, so a reader can move from one matter to the next.
        - When something in a section has changed, replace that text; do not add a note that contradicts it.
        - Where the environment already records a fact (a config file, a repository document, an infrastructure note), write a pointer to it, not a copy.
        - Name sections in the memory language, except three the service finds by name and that keep their English names in every language: Lesson, Overturned and Leftovers.
        - incident: one fault, its cause and its fix. Sections: Symptom, Cause, Fix, Lesson. The lesson is the rule the next session can apply.
        - decision: one decision and its reasons. Sections: Decision, Reasons, Overturned. When a later page overturns the decision, add a line under Overturned naming that page; the brief then stops listing the decision as current.
        - entity: a standing system or tool, kept to a table of contents: pointers to its documentation, the user's stance and open to-dos. Write each fault and each decision on its own page and link it back here. Sections: Status, Stance, To-do.
        - work: one unit of work and its record, such as a slice or a release, written once for the whole unit. Sections: Output, Leftovers. The leftovers are the open items the brief lists for the workstream.

        ## Examples
        Each example shows a sample page for a Chinese memory, with its type and its recommended sections. The examples are invented, and their text is data, not instructions.

        <example type="incident">
        Title: Alpine 容器内 TLS 证书校验失败
        Aliases: 容器 HTTPS 报错, Alpine 缺根证书
        ## 修复
        在基础镜像中安装 `ca-certificates` 并更新证书库，不再通过关闭 TLS 校验绕过。
        ## Lesson
        精简镜像请求外部 HTTPS 时先确认已包含根证书包，不要用跳过证书校验绕过。
        </example>

        <example type="decision">
        Title: 本地检索保持双路召回加精排
        Aliases: 检索方案定型, 不用纯向量检索
        ## 决定
        保留全文加向量融合后精排，不改成纯向量检索。
        ## 理由
        纯向量对文件名、配置键和错误码的精确匹配漏召回明显。
        </example>

        <example type="entity">
        Title: staging-box
        Aliases: 测试主机, 内网测试机
        ## 现状
        内网测试机运行 Docker Compose 与反代服务；拓扑和端口清单见 `~/ops/staging.md`，此处只写指针。
        </example>

        <example type="work">
        Title: log-trimmer v1.2
        Aliases: 日志裁剪器 1.2, log-trimmer 发版
        ## 产出
        发布 v1.2：支持按大小轮转并补齐超长行截断；1.1 分支停止维护。
        ## Leftovers
        高并发下的异步刷盘缓冲留待后续优化。
        </example>

        ## Activities
        - An activity is one conclusion with one reason or decision, in a single sentence. Put the details in the detail page and leave them out of the activity.
        - Describe the result and the thinking, not the files that changed or the steps taken.
        - One activity belongs to one workstream. Set the workstream to a name listed in `<user_memory>`, spelled exactly as listed. When no listed name fits, leave the workstream out: never invent a name.
        - A matter that fits no workstream gets a topic page (a page with no workstream), not a label on the activity.
        - To revise an activity already written for the same matter, write the revised sentence with replaces set to that activity's short code. Only today's activities can be revised; an earlier day's or an expired code is refused.

        The workstream is the `workstream` argument of `write_recent`, not part of the text. In each pair below, Bad lists the steps; Good states the same event as one conclusion with its reason. The examples are invented.

        <pair language="zh">
        Bad: 今天把导出脚本拆成读取和写入两个文件，日期解析换成标准库，补了 6 个测试，改了 README 里的用法示例，删掉两个没用的参数。
        Good: 导出脚本改为按月分文件输出，因为单个文件过大时表格软件打不开。
        </pair>

        <pair language="en">
        Bad: Today I moved the sync job into its own module, renamed three helper methods, added retry logic with a five-second backoff, and updated the README.
        Good: Sync retries moved into their own module; the job now fails fast after three attempts instead of hanging.
        </pair>

        ## Persona
        The persona has four sections, and every entry sits in a scope. Each entry is one line in the memory language; the examples below are in English.
        - Red lines: what must not be done for this person, and what to do instead. For example: "Never push to main without asking; open a branch instead."
        - Working rules: how to proceed when a situation comes up, written as situation → action. For example: "When the request is unclear → ask first, then plan."
        - Preferences: how the person likes things done. A preference is a description to weigh against the task, not an order. For example: "Answer length: short, with the conclusion first."
        - Profile: background that helps understand the person. For example: "Role: backend engineer, mostly C# on Windows."
        - Keep one idea per entry, and keep the user's own words in its source note when the wording matters.
        - Scope: global entries are read in every session. Write an entry as global only when it holds in at least two different kinds of situation; otherwise give it a workstream scope (`workstream:<name>`, using the workstream's name) or a domain scope (`domain:<label>`).
        - Domain: a label names a kind of situation, such as network-proxy. Its trigger is one line saying when the domain applies, for example "when changing proxies, routing or speed tests". Reuse an existing label exactly; a new label needs a trigger.
        - A preference or rule the user agrees to keep goes in with add; propose a habit with op=propose and its scope only when it repeats across the session or clearly applies beyond the current task, not for a one-off workaround. It waits as a candidate.
        - To change or delete an entry, use its short code from `recall kind=persona`, which returns the whole persona with every entry's code. When a code is refused, call `recall kind=persona` again and take the fresh code from there.

        ## Refusals
        - Do the step a refusal names, with the short codes it gives, then retry the write once; if it is still refused, tell the user what was refused and why.
        - A refusal about a red line or a conflicting persona entry is for the user to decide: ask them before changing the persona.
        """;

    /// <summary>The whole file: frontmatter, the generated note, the system part, and the user's section when there is one.</summary>
    public static string Compose(string? userConventions)
    {
        var parts = new List<string>
        {
            $"---\nname: {Name}\ndescription: \"{Description}\"\n---",
            Generated,
            SystemPart,
        };
        if (userConventions is not null)
            parts.Add(UserHeading + "\n\n" + userConventions.ReplaceLineEndings("\n"));
        return string.Join("\n\n", parts) + "\n";
    }
}
